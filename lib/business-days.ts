/** Date → ローカル基準の yyyy-MM-dd。 */
export function formatYmd(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

/** yyyy-MM-dd → ローカルタイムゾーンの Date（0:00）。 */
export function parseYmd(s: string): Date {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(y, m - 1, d);
}

/** 土日または祝日か。 */
export function isNonBusinessDay(d: Date): boolean {
  const dow = d.getDay();
  return dow === 0 || dow === 6 || HOLIDAYS.has(formatYmd(d));
}

/** その日が非営業日なら直前の営業日まで遡る。営業日ならそのまま返す。 */
export function previousBusinessDay(d: Date): Date {
  const out = new Date(d);
  while (isNonBusinessDay(out)) {
    out.setDate(out.getDate() - 1);
  }
  return out;
}

/**
 * 出荷予定日の既定値。
 * 貸出開始日の2日前。その日が土日祝なら、その前の営業日にずらす。
 */
export function defaultPlannedShipDate(start: Date): Date {
  const d = new Date(start);
  d.setDate(d.getDate() - 2);
  return previousBusinessDay(d);
}
